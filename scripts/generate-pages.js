#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.resolve(__dirname, '..');
const CATALOGUE_FILE = path.join(ROOT, 'catalogue.js');
const OUTPUT_ROOT = path.join(ROOT, 'colouring-pages');
const SITEMAP_FILE = path.join(ROOT, 'sitemap.xml');
const ROBOTS_FILE = path.join(ROOT, 'robots.txt');
const SITE_URL = 'https://xarky.github.io/little-colour-library/';
const ROBOTS_CONTENT = `User-agent: *
Allow: /

Sitemap: ${SITE_URL}sitemap.xml
`;
const GENERATED_MARKER = '<!-- Generated by scripts/generate-pages.js; do not edit. -->';
const ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function readCatalogue() {
  const source = fs.readFileSync(CATALOGUE_FILE, 'utf8');
  const window = {};
  vm.runInNewContext(source, { window }, {
    filename: 'catalogue.js',
    timeout: 1000
  });

  if (!Array.isArray(window.COLOUR_CATALOGUE)) {
    throw new Error('catalogue.js must define window.COLOUR_CATALOGUE as an array.');
  }

  const ids = new Set();
  return window.COLOUR_CATALOGUE.map((item, index) => {
    const label = `catalogue entry ${index + 1}`;
    if (!item || typeof item !== 'object' || Array.isArray(item)) {
      throw new Error(`${label} must be an object.`);
    }

    for (const field of ['id', 'title', 'category', 'description', 'preview', 'pdf']) {
      if (typeof item[field] !== 'string' || !item[field].trim()) {
        throw new Error(`${label} must have a non-empty "${field}" string.`);
      }
    }

    if (!ID_PATTERN.test(item.id)) {
      throw new Error(`${label} has an invalid id "${item.id}". Use lowercase letters, numbers and hyphens.`);
    }
    if (ids.has(item.id)) {
      throw new Error(`Duplicate catalogue id "${item.id}".`);
    }
    ids.add(item.id);

    if (!Array.isArray(item.tags) || !item.tags.every(tag => typeof tag === 'string')) {
      throw new Error(`${label} must have a tags array containing only strings.`);
    }

    for (const [field, folder] of [['preview', 'previews'], ['pdf', 'pdfs']]) {
      const asset = item[field];
      if (!asset.startsWith(`assets/${folder}/`) || asset.includes('\\') ||
          path.posix.normalize(asset) !== asset || asset.slice(`assets/${folder}/`.length).includes('/')) {
        throw new Error(`${label} has an invalid ${field} path "${asset}".`);
      }
      const absoluteAsset = path.resolve(ROOT, asset);
      if (!absoluteAsset.startsWith(path.resolve(ROOT, 'assets') + path.sep) ||
          !fs.existsSync(absoluteAsset) || !fs.statSync(absoluteAsset).isFile()) {
        throw new Error(`${label} references a missing ${field} file: ${asset}`);
      }
    }

    return item;
  });
}

function renderPage(item) {
  const canonicalUrl = new URL(`colouring-pages/${item.id}/`, SITE_URL).href;
  const preview = `../../${item.preview}`;
  const pdf = `../../${item.pdf}`;
  const alt = item.alt || `Colouring page illustration: ${item.title}`;

  return `${GENERATED_MARKER}
<!doctype html>
<html lang="en-GB">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escapeHtml(item.description)}">
  <link rel="canonical" href="${escapeHtml(canonicalUrl)}">
  <title>${escapeHtml(item.title)} | Free Printable Colouring Page</title>
  <style>
    :root{font-family:system-ui,-apple-system,'Segoe UI',sans-serif;color:#23352f;background:#f7f5ef}
    *{box-sizing:border-box}
    body{margin:0}
    a{color:#24594c}
    a:focus-visible{outline:3px solid #147c78;outline-offset:3px}
    main{max-width:760px;margin:0 auto;padding:32px 22px 56px}
    nav{margin-bottom:28px}
    article{background:#fff;border:1px solid #e0e5dc;border-radius:19px;padding:24px}
    img{display:block;width:100%;max-height:70vh;object-fit:contain;background:#fff}
    h1{line-height:1.15}
    .category{color:#397463;font-size:.85rem;font-weight:800;letter-spacing:.07em;text-transform:uppercase}
    .description{color:#4f6057;line-height:1.6}
    .pdf{display:inline-block;margin-top:8px;padding:13px 16px;border-radius:10px;background:#24594c;color:#fff;font-weight:750;text-decoration:none}
  </style>
</head>
<body>
  <main>
    <nav aria-label="Breadcrumb"><a href="../../">Little Colour Library</a> / ${escapeHtml(item.title)}</nav>
    <article>
      <p class="category">${escapeHtml(item.category)}</p>
      <h1>${escapeHtml(item.title)}</h1>
      <p class="description">${escapeHtml(item.description)}</p>
      <img src="${escapeHtml(preview)}" alt="${escapeHtml(alt)}">
      <p><a class="pdf" href="${escapeHtml(pdf)}">Open printable PDF for ${escapeHtml(item.title)}</a></p>
    </article>
  </main>
</body>
</html>
`;
}

function renderSitemap(catalogue) {
  const urls = [
    SITE_URL,
    ...catalogue.map(item => new URL(`colouring-pages/${item.id}/`, SITE_URL).href)
  ];
  const entries = urls.map(url => `  <url>\n    <loc>${escapeXml(url)}</loc>\n  </url>`).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`;
}

function removeStaleGeneratedPages(currentIds) {
  if (!fs.existsSync(OUTPUT_ROOT)) return 0;

  let removed = 0;
  for (const entry of fs.readdirSync(OUTPUT_ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory() || !ID_PATTERN.test(entry.name) || currentIds.has(entry.name)) continue;

    const pageFile = path.join(OUTPUT_ROOT, entry.name, 'index.html');
    if (!fs.existsSync(pageFile) || !fs.readFileSync(pageFile, 'utf8').startsWith(GENERATED_MARKER)) continue;

    fs.unlinkSync(pageFile);
    if (fs.readdirSync(path.dirname(pageFile)).length === 0) {
      fs.rmdirSync(path.dirname(pageFile));
    }
    removed += 1;
  }
  return removed;
}

function main() {
  const catalogue = readCatalogue();
  fs.mkdirSync(OUTPUT_ROOT, { recursive: true });

  for (const item of catalogue) {
    const outputDirectory = path.join(OUTPUT_ROOT, item.id);
    fs.mkdirSync(outputDirectory, { recursive: true });
    fs.writeFileSync(path.join(outputDirectory, 'index.html'), renderPage(item), 'utf8');
  }

  const removed = removeStaleGeneratedPages(new Set(catalogue.map(item => item.id)));
  fs.writeFileSync(SITEMAP_FILE, renderSitemap(catalogue), 'utf8');
  fs.writeFileSync(ROBOTS_FILE, ROBOTS_CONTENT, 'utf8');
  console.log(`Generated ${catalogue.length} colouring pages, sitemap.xml and robots.txt${removed ? `; removed ${removed} stale page${removed === 1 ? '' : 's'}` : ''}.`);
}

try {
  main();
} catch (error) {
  console.error(`Page generation failed: ${error.message}`);
  process.exitCode = 1;
}
